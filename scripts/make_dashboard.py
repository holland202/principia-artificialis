class BuildError(Exception):
    pass


def validate_card(card):
    """Return the card if every rule holds; raise BuildError naming the first rule that does not."""
    if not isinstance(card, dict):
        raise BuildError("card is not an object")
    for key in ("schemaVersion", "id", "title", "question", "reviewedAt", "reviewedBy", "states", "observations",
                "adverse", "openDecisions", "nextReview", "timeline", "credits", "sources"):
        if key not in card or card[key] in (None, "", []):
            raise BuildError(f"missing or empty field: {key}")
    if card["schemaVersion"] != "0.1":
        raise BuildError("unknown schemaVersion")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(card["reviewedAt"])):
        raise BuildError("reviewedAt must be YYYY-MM-DD")
    ids = set()
    for s in card["sources"]:
        if not isinstance(s, dict) or not s.get("id") or not s.get("label") or not s.get("url"):
            raise BuildError("source needs id, label and url")
        if s["id"] in ids:
            raise BuildError(f"duplicate source id: {s['id']}")
        if not str(s["url"]).startswith("https://github.com/"):
            raise BuildError(f"source url outside the allowlist (https://github.com/): {s['id']}")
        ids.add(s["id"])

    def refs(item, where):
        src = item.get("sourceIds") if isinstance(item, dict) else None
        if not src:
            raise BuildError(f"{where}: no sourceIds")
        for sid in src:
            if sid not in ids:
                raise BuildError(f"{where}: unknown source id {sid}")

    states = card["states"]
    if set(states) != set(VOCAB):
        raise BuildError(f"states must be exactly {sorted(VOCAB)}")
    for dim, st in states.items():
        if not isinstance(st, dict) or st.get("value") not in VOCAB[dim]:
            raise BuildError(f"state {dim}: value not in its own vocabulary")
        refs(st, f"state {dim}")
    # No promotion without execution: a claim cannot be judged, and nothing reproduced, before a registered run.
    if states["execution"]["value"] not in EXECUTED:
        if states["claim"]["value"] not in ("not-tested", "insufficient-evidence"):
            raise BuildError("claim assessed without a registered execution")
        if states["reproduction"]["value"] == "independent-reproduction-documented":
            raise BuildError("reproduction documented without a registered execution")
    for i, ob in enumerate(card["observations"]):
        for key in ("text", "originator", "limitation"):
            if not isinstance(ob, dict) or not str(ob.get(key, "")).strip():
                raise BuildError(f"observation {i}: missing {key} (a number never appears without its limitation)")
        refs(ob, f"observation {i}")
    for group in ("adverse", "openDecisions", "credits"):
        for i, item in enumerate(card[group]):
            refs(item, f"{group} {i}")
    for i, ev in enumerate(card["timeline"]):
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(ev.get("date", ""))):
            raise BuildError(f"timeline {i}: date must be YYYY-MM-DD")
        refs(ev, f"timeline {i}")
    return card


def parse_index(text):
    """Counts and kept refutations from the generated NOTES_INDEX.md; raise BuildError if its shape is unknown."""
    head = re.search(r"\*\*(\d+) notes indexed across both series \((\d+) numbers claimed by multiple notes", text)
    gen = re.search(r"Auto-generated by `scripts/make_index\.py` \(v\d+\) on (\d{4}-\d{2}-\d{2})", text)
    tiers = re.search(r"Verified (\d+), Draft (\d+), Speculative (\d+), Unmapped (\d+)", text)
    if not (head and gen and tiers):
        raise BuildError("NOTES_INDEX.md: header, generation date or tier line not found")
    rows = [r for r in text.splitlines() if re.match(r"\| #\d", r)]
    if len(rows) != int(head.group(1)):
        raise BuildError(f"NOTES_INDEX.md: header says {head.group(1)} notes, table has {len(rows)} rows")
    kept = []
    authors = {}
    for r in rows:
        cells = [c.strip() for c in r.strip("|").split("|")]
        if len(cells) < 5:
            raise BuildError("NOTES_INDEX.md: malformed row")
        authors[cells[4]] = authors.get(cells[4], 0) + 1
        if "⚠" in cells[2]:
            m = re.match(r"\[(.+)\]\((.+)\)$", cells[1])
            if not m:
                raise BuildError("NOTES_INDEX.md: malformed note link")
            kept.append({"num": cells[0].replace("⚡", "").strip(), "title": m.group(1), "path": m.group(2)})
    return {"total": int(head.group(1)), "collisions": int(head.group(2)), "generated": gen.group(1),
            "tiers": dict(zip(("Verified", "Draft", "Speculative", "Unmapped"), map(int, tiers.groups()))),
            "kept": kept, "authors": authors}


