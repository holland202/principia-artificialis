"""Generate the dashboard's research-status sections from their sources, so they cannot drift by hand.

    python scripts/make_dashboard.py          rewrite the generated blocks in dashboard.html
    python scripts/make_dashboard.py --check  exit 1 if dashboard.html differs from what the sources give

Sources (the only ones):
  NOTES_INDEX.md                    notes program status board (itself generated by scripts/make_index.py)
  data/dashboard/egrr_card.json     reviewed EGRR research card (schema 0.1, after Putluru Sandeep's
                                    2026-10-20 design proposal)
  data/dashboard/cards/*.json       further research cards in the same schema, one file per study, rendered in
                                    file-name order (the portal half of the same proposal, added 2026-10-22)

Fail-closed (C-BUILD): a card that does not validate, or an index that cannot be parsed, stops the build with
exit 2 and writes nothing. Nothing is ever rendered from a missing or partial source.
Exit codes: 0 ok / up to date, 1 --check found drift, 2 could not build.
Stdlib only. Written by Claude (Anthropic, Opus 5.5), 2026-10-22, at Chad Holland's direction.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "NOTES_INDEX.md"
CARD = ROOT / "data" / "dashboard" / "egrr_card.json"
CARDS_DIR = ROOT / "data" / "dashboard" / "cards"
PAGE = ROOT / "dashboard.html"

# Each dimension keeps its own vocabulary; a value from one dimension is never shown in another (METHOD.md §4).
VOCAB = {
    "question": {"speculative-proposal": "Speculative proposal",
                 "admitted-for-protocol-development": "Admitted for protocol development only",
                 "admitted-for-study": "Admitted for a registered study",
                 "declined": "Declined", "parked": "Parked"},
    "protocol": {"not-drafted": "Not drafted", "draft-under-review": "Draft under review, not frozen",
                 "review-pending": "Review pending", "frozen": "Frozen (registered)"},
    "execution": {"not-tested": "Not executed", "exploratory-observation-reported": "Exploratory observation reported",
                  "registered-experiment-running": "Registered run in progress",
                  "registered-experiment-executed": "Registered experiment executed", "could-not-run": "Could not run"},
    "engineering": {"not-submitted": "Not submitted", "changes-requested": "Changes requested",
                    "accepted": "Accepted at constructed scope", "blocked": "Blocked"},
    "reproduction": {"none-documented": "None documented", "rerun-reported": "Same-code re-run reported",
                     "independent-reproduction-documented": "Independent reproduction documented"},
    "claim": {"not-tested": "Not tested", "insufficient-evidence": "Insufficient evidence",
              "supported": "Supported", "refuted": "Refuted"},
}
DIMENSION_LABEL = {"question": "Question", "protocol": "Protocol", "execution": "Study execution",
                   "engineering": "Engineering qualification", "reproduction": "Independent reproduction",
                   "claim": "Claim assessment"}
EXECUTED = {"registered-experiment-executed"}


class BuildError(Exception):
    pass


def validate_card(card):
    """Return the card if every rule holds; raise BuildError naming the first rule that does not."""
    if not isinstance(card, dict):
        raise BuildError("card is not an object")
    for key in ("schemaVersion", "id", "title", "question", "reviewedAt", "reviewedBy", "states", "observations",
                "adverse", "openDecisions", "nextReview", "timeline", "credits", "sources"):
        if key not in card or card[key] in (None, "", []):
            raise BuildError(f"missing or empty field: {key}")
    if card["schemaVersion"] != "0.1":
        raise BuildError("unknown schemaVersion")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(card["reviewedAt"])):
        raise BuildError("reviewedAt must be YYYY-MM-DD")
    ids = set()
    for s in card["sources"]:
        if not isinstance(s, dict) or not s.get("id") or not s.get("label") or not s.get("url"):
            raise BuildError("source needs id, label and url")
        if s["id"] in ids:
            raise BuildError(f"duplicate source id: {s['id']}")
        if not str(s["url"]).startswith("https://github.com/"):
            raise BuildError(f"source url outside the allowlist (https://github.com/): {s['id']}")
        ids.add(s["id"])

    def refs(item, where):
        src = item.get("sourceIds") if isinstance(item, dict) else None
        if not src:
            raise BuildError(f"{where}: no sourceIds")
        for sid in src:
            if sid not in ids:
                raise BuildError(f"{where}: unknown source id {sid}")

    states = card["states"]
    if set(states) != set(VOCAB):
        raise BuildError(f"states must be exactly {sorted(VOCAB)}")
    for dim, st in states.items():
        if not isinstance(st, dict) or st.get("value") not in VOCAB[dim]:
            raise BuildError(f"state {dim}: value not in its own vocabulary")
        refs(st, f"state {dim}")
    # No promotion without execution: a claim cannot be judged, and nothing reproduced, before a registered run.
    if states["execution"]["value"] not in EXECUTED:
        if states["claim"]["value"] not in ("not-tested", "insufficient-evidence"):
            raise BuildError("claim assessed without a registered execution")
        if states["reproduction"]["value"] == "independent-reproduction-documented":
            raise BuildError("reproduction documented without a registered execution")
    for i, ob in enumerate(card["observations"]):
        for key in ("text", "originator", "limitation"):
            if not isinstance(ob, dict) or not str(ob.get(key, "")).strip():
                raise BuildError(f"observation {i}: missing {key} (a number never appears without its limitation)")
        refs(ob, f"observation {i}")
    for group in ("adverse", "openDecisions", "credits"):
        for i, item in enumerate(card[group]):
            refs(item, f"{group} {i}")
    for i, ev in enumerate(card["timeline"]):
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(ev.get("date", ""))):
            raise BuildError(f"timeline {i}: date must be YYYY-MM-DD")
        refs(ev, f"timeline {i}")
    return card


def parse_index(text):
    """Counts and kept refutations from the generated NOTES_INDEX.md; raise BuildError if its shape is unknown."""
    head = re.search(r"\*\*(\d+) notes indexed across both series \((\d+) numbers claimed by multiple notes", text)
    gen = re.search(r"Auto-generated by `scripts/make_index\.py` \(v\d+\) on (\d{4}-\d{2}-\d{2})", text)
    tiers = re.search(r"Verified (\d+), Draft (\d+), Speculative (\d+), Unmapped (\d+)", text)
    if not (head and gen and tiers):
        raise BuildError("NOTES_INDEX.md: header, generation date or tier line not found")
    rows = [r for r in text.splitlines() if re.match(r"\| #\d", r)]
    if len(rows) != int(head.group(1)):
        raise BuildError(f"NOTES_INDEX.md: header says {head.group(1)} notes, table has {len(rows)} rows")
    kept = []
    for r in rows:
        cells = [c.strip() for c in r.strip("|").split("|")]
        if len(cells) < 3:
            raise BuildError("NOTES_INDEX.md: malformed row")
        if "⚠" in cells[2]:
            m = re.match(r"\[(.+)\]\((.+)\)$", cells[1])
            if not m:
                raise BuildError("NOTES_INDEX.md: malformed note link")
            kept.append({"num": cells[0].replace("⚡", "").strip(), "title": m.group(1), "path": m.group(2)})
    return {"total": int(head.group(1)), "collisions": int(head.group(2)), "generated": gen.group(1),
            "tiers": dict(zip(("Verified", "Draft", "Speculative", "Unmapped"), map(int, tiers.groups()))),
            "kept": kept}


E = html.escape
REPO = "https://github.com/holland202/principia-artificialis/blob/main/"


def render_status(ix):
    t = ix["tiers"]
    tiles = "".join(f'<div class="tile"><b>{t[k]}</b><span>{k}</span></div>'
                    for k in ("Verified", "Draft", "Speculative", "Unmapped"))
    kept = "".join(f'<li><a href="{E(REPO + k["path"])}">{E(k["num"])} · {E(k["title"])}</a></li>'
                   for k in ix["kept"])
    return (f'<div class="tiles" aria-label="Notes by status tier">{tiles}</div>\n'
            f'<p class="muted"><strong>{ix["total"]} notes</strong>; {ix["collisions"]} note numbers are claimed by '
            f'more than one note and shown, not hidden. "Verified" means a note\'s reference code prints its numbers; '
            f'it is not independent validation. Counts come from '
            f'<a href="{REPO}NOTES_INDEX.md">NOTES_INDEX.md</a> (generated {E(ix["generated"])}).</p>\n'
            f'<details><summary>{len(ix["kept"])} notes keep a refuted prediction (⚠): failures stay on the record'
            f'</summary><ul class="kept">{kept}</ul></details>')


def card_slug(card):
    """A stable HTML id from the card id: lowercase letters, digits and hyphens only."""
    slug = re.sub(r"[^a-z0-9]+", "-", str(card["id"]).lower()).strip("-")
    if not slug:
        raise BuildError("card id gives an empty HTML id")
    return slug


def render_card(card, title_id="egrr-title", source_path="data/dashboard/egrr_card.json"):
    src = {s["id"]: s for s in card["sources"]}

    def links(ids):
        return " ".join(f'<a class="src" href="{E(src[i]["url"])}">{E(src[i]["label"])}</a>' for i in ids)

    chips = "".join(f'<span><em>{E(DIMENSION_LABEL[d])}:</em> {E(VOCAB[d][card["states"][d]["value"]])}</span>'
                    for d in VOCAB)
    obs = "".join(f'<li>{E(o["text"])} <span class="who">— {E(o["originator"])}.</span> '
                  f'<strong>Limit:</strong> {E(o["limitation"])} {links(o["sourceIds"])}</li>'
                  for o in card["observations"])
    adv = "".join(f'<li>{E(a["text"])} {links(a["sourceIds"])}</li>' for a in card["adverse"])
    dec = "".join(f'<li>{E(d["text"])} {links(d["sourceIds"])}</li>' for d in card["openDecisions"])
    tl = "".join(f'<li><time datetime="{E(t["date"])}">{E(t["date"])}</time> {E(t["text"])} {links(t["sourceIds"])}</li>'
                 for t in card["timeline"])
    cr = "".join(f'<li><strong>{E(c["name"])}</strong>: {E(c["role"])}</li>' for c in card["credits"])
    return (f'<div class="tag">Research card · {E(card["id"])} · reviewed {E(card["reviewedAt"])}</div>\n'
            f'<h3 id="{E(title_id)}">{E(card["title"])}</h3>\n<p>{E(card["question"])}</p>\n'
            f'<div class="research-statuses" aria-label="Status, one dimension at a time">{chips}</div>\n'
            f'<div class="grid"><div><h4>Reported observations</h4><ul>{obs}</ul></div>'
            f'<div><h4>Adverse and unresolved evidence</h4><ul>{adv}</ul></div></div>\n'
            f'<div class="grid"><div><h4>Open decisions</h4><ul>{dec}</ul>'
            f'<p><strong>Next review:</strong> {E(card["nextReview"])}</p></div>'
            f'<div><h4>Timeline</h4><ul class="timeline">{tl}</ul></div></div>\n'
            f'<h4>Credit</h4><ul>{cr}</ul>\n'
            f'<p class="attribution">Card reviewed by {E(card["reviewedBy"])}. Attribution does not imply scientific '
            f'validation. Source: <a href="{E(REPO + source_path)}">{E(source_path.rsplit("/", 1)[-1])}</a>.</p>')


def load_cards(directory=None):
    """[(published path, card object)] for every *.json in data/dashboard/cards, in file-name order."""
    directory = CARDS_DIR if directory is None else Path(directory)
    if not directory.is_dir():
        return []
    return [(f"data/dashboard/cards/{p.name}", json.loads(p.read_text(encoding="utf-8")))
            for p in sorted(directory.glob("*.json"))]


def render_cards(featured, extra):
    """The further research cards. Ids must be unique across every card on the page, the featured one included."""
    seen = {featured["id"]}
    out = []
    for path, card in extra:
        validate_card(card)
        if card["id"] in seen:
            raise BuildError(f"duplicate card id: {card['id']}")
        seen.add(card["id"])
        tid = card_slug(card) + "-title"
        out.append(f'<article class="research-card" aria-labelledby="{E(tid)}">\n'
                   f'{render_card(card, title_id=tid, source_path=path)}\n</article>')
    if not out:
        return '<p class="muted">No further research cards yet.</p>'
    return ('<h3 class="cards-heading">More research cards</h3>\n<p class="muted">Each card below follows the same '
            'schema and rules as the featured one: every status names its source, and a number never appears '
            'without its limitation. The card format follows Putluru Sandeep\'s 2026-10-20 design proposal. '
            'Order is by file name, not by importance.</p>\n' + "\n".join(out))


def build(page_text, index_text, card_obj, extra_cards=None):
    featured = validate_card(card_obj)
    extra = load_cards() if extra_cards is None else extra_cards
    blocks = {"status-board": render_status(parse_index(index_text)),
              "egrr-card": render_card(featured),
              "research-cards": render_cards(featured, extra)}
    out = page_text
    for name, body in blocks.items():
        pat = re.compile(rf"(<!-- generated:{name}:start -->\n).*?(<!-- generated:{name}:end -->)", re.S)
        if len(pat.findall(out)) != 1:
            raise BuildError(f"dashboard.html: marker pair for {name} not found exactly once")
        out = pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), out)
    return out


def main(argv):
    check = "--check" in argv
    try:
        page = PAGE.read_text(encoding="utf-8")
        new = build(page, INDEX.read_text(encoding="utf-8"), json.loads(CARD.read_text(encoding="utf-8")))
    except (OSError, ValueError, BuildError) as exc:
        print(f"COULD NOT BUILD: {exc}")
        return 2
    if check:
        if new != page:
            print("DRIFT: dashboard.html does not match its sources; run python scripts/make_dashboard.py")
            return 1
        print("dashboard.html matches NOTES_INDEX.md, egrr_card.json and data/dashboard/cards/")
        return 0
    if new != page:
        PAGE.write_text(new, encoding="utf-8")
        print("dashboard.html updated")
    else:
        print("dashboard.html already current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
