# Where a study stands, derived only from its card's own states (never typed by hand). Order matters: the first
# rule that matches wins, from the furthest stage back.
STAGES = ("Proposed", "Registered", "Running", "Scored", "Reproduced")


def stage_of(card):
    st = {d: card["states"][d]["value"] for d in VOCAB}
    if st["reproduction"] == "independent-reproduction-documented":
        return "Reproduced"
    if st["execution"] == "registered-experiment-executed":
        return "Scored"
    if st["execution"] == "registered-experiment-running":
        return "Running"
    if st["protocol"] == "frozen":
        return "Registered"
    return "Proposed"


def render_overview(ix, cards):
    """The program at a glance: every research card placed on one pipeline, plus counts from NOTES_INDEX.md."""
    cols = []
    for stage in STAGES:
        items = "".join(
            f'<li><a href="#{E(card_slug(c) if c is not cards[0] else "egrr")}-title">{E(c["id"])}</a>'
            + (' <span class="refuted">refuted</span>' if c["states"]["claim"]["value"] == "refuted" else "")
            + "</li>" for c in cards if stage_of(c) == stage)
        cols.append(f'<div class="stage"><h4>{E(stage)}</h4><ul>{items or "<li class=muted>none</li>"}</ul></div>')
    named = {a: n for a, n in ix["authors"].items() if a not in ("—", "")}
    unnamed = ix["total"] - sum(named.values())
    who = "".join(f'<li>{E(a)}: {n}</li>' for a, n in sorted(named.items(), key=lambda kv: (-kv[1], kv[0])))
    return (f'<div class="pipeline" aria-label="Research cards by stage">{"".join(cols)}</div>\n'
            f'<p class="muted">Stage is derived from each card\'s own statuses: Registered means a frozen protocol, '
            f'Running a registered run in progress, Scored an executed registered run, Reproduced an independent '
            f'reproduction on record. A stage is not a verdict.</p>\n'
            f'<div class="tiles" aria-label="Program counts">'
            f'<div class="tile"><b>{len(cards)}</b><span>research cards</span></div>'
            f'<div class="tile"><b>{ix["total"]}</b><span>research notes</span></div>'
            f'<div class="tile"><b>{len(ix["kept"])}</b><span>notes keep a refuted prediction</span></div>'
            f'<div class="tile"><b>{ix["total"] - unnamed}</b><span>notes name their author</span></div></div>\n'
            f'<details><summary>Notes by author, as each note names it ({unnamed} name no author)</summary>'
            f'<ul class="kept">{who}</ul></details>\n'
            f'<p class="muted">Not shown, because it cannot yet be counted reliably from the notes: how many predictions '
            f'are registered, and how many are still unrun.</p>')


def card_slug(card):
    """A stable HTML id from the card id: lowercase letters, digits and hyphens only."""
    slug = re.sub(r"[^a-z0-9]+", "-", str(card["id"]).lower()).strip("-")
    if not slug:
        raise BuildError("card id gives an empty HTML id")
    return slug


def render_card(card, title_id="egrr-title", source_path="data/dashboard/egrr_card.json"):
    src = {s["id"]: s for s in card["sources"]}

    def links(ids):
        return " ".join(f'<a class="src" href="{E(src[i]["url"])}">{E(src[i]["label"])}</a>' for i in ids)

    chips = "".join(f'<span><em>{E(DIMENSION_LABEL[d])}:</em> {E(VOCAB[d][card["states"][d]["value"]])}</span>'
                    for d in VOCAB)
    obs = "".join(f'<li>{E(o["text"])} <span class="who">— {E(o["originator"])}.</span> '
                  f'<strong>Limit:</strong> {E(o["limitation"])} {links(o["sourceIds"])}</li>'
                  for o in card["observations"])
    adv = "".join(f'<li>{E(a["text"])} {links(a["sourceIds"])}</li>' for a in card["adverse"])
    dec = "".join(f'<li>{E(d["text"])} {links(d["sourceIds"])}</li>' for d in card["openDecisions"])
    tl = "".join(f'<li><time datetime="{E(t["date"])}">{E(t["date"])}</time> {E(t["text"])} {links(t["sourceIds"])}</li>'
                 for t in card["timeline"])
    cr = "".join(f'<li><strong>{E(c["name"])}</strong>: {E(c["role"])}</li>' for c in card["credits"])
    return (f'<div class="tag">Research card · {E(card["id"])} · reviewed {E(card["reviewedAt"])}</div>\n'
            f'<h3 id="{E(title_id)}">{E(card["title"])}</h3>\n<p>{E(card["question"])}</p>\n'
            f'<div class="research-statuses" aria-label="Status, one dimension at a time">{chips}</div>\n'
            f'<div class="grid"><div><h4>Reported observations</h4><ul>{obs}</ul></div>'
            f'<div><h4>Adverse and unresolved evidence</h4><ul>{adv}</ul></div></div>\n'
            f'<div class="grid"><div><h4>Open decisions</h4><ul>{dec}</ul>'
            f'<p><strong>Next review:</strong> {E(card["nextReview"])}</p></div>'
            f'<div><h4>Timeline</h4><ul class="timeline">{tl}</ul></div></div>\n'
            f'<h4>Credit</h4><ul>{cr}</ul>\n'
            f'<p class="attribution">Card reviewed by {E(card["reviewedBy"])}. Attribution does not imply scientific '
            f'validation. Source: <a href="{E(REPO + source_path)}">{E(source_path.rsplit("/", 1)[-1])}</a>.</p>')


def load_cards(directory=None):
    """[(published path, card object)] for every *.json in data/dashboard/cards, in file-name order."""
    directory = CARDS_DIR if directory is None else Path(directory)
    if not directory.is_dir():
        return []
    return [(f"data/dashboard/cards/{p.name}", json.loads(p.read_text(encoding="utf-8")))
            for p in sorted(directory.glob("*.json"))]


def render_cards(featured, extra):
    """The further research cards. Ids must be unique across every card on the page, the featured one included."""
    seen = {featured["id"]}
    out = []
    for path, card in extra:
        validate_card(card)
        if card["id"] in seen:
            raise BuildError(f"duplicate card id: {card['id']}")
        seen.add(card["id"])
        tid = card_slug(card) + "-title"
        out.append(f'<article class="research-card" aria-labelledby="{E(tid)}">\n'
                   f'{render_card(card, title_id=tid, source_path=path)}\n</article>')
    if not out:
        return '<p class="muted">No further research cards yet.</p>'
    return ('<h3 class="cards-heading">More research cards</h3>\n<p class="muted">Each card below follows the same '
            'schema and rules as the featured one: every status names its source, and a number never appears '
            'without its limitation. The card format follows Putluru Sandeep\'s 2026-10-20 design proposal. '
            'Order is by file name, not by importance.</p>\n' + "\n".join(out))


EVIDENCE_LABELS = {
    "reproduced": "Independent study reproduction",
    "documentary": "Independent documentary reproduction",
    "reported": "Author-reported",
    "failure": "Failure kept",
    "untested": "Untested",
    "unresolved": "Unresolved",
    "reference": "Reference",
}
PINNED_SOURCE = re.compile(
    r"https://github\.com/holland202/principia-artificialis/blob/[0-9a-f]{40}/"
    r"[A-Za-z0-9_./-]+(?:#[A-Za-z0-9_-]+)?"
)


def text_field(obj, key):
    value = obj.get(key) if isinstance(obj, dict) else None
    return isinstance(value, str) and bool(value.strip())


def validate_constellation(data):
    if (not text_field(data, "reviewedAt") or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", data["reviewedAt"])
            or not text_field(data, "provenance")):
        raise BuildError("constellation: missing review date or provenance")
    nodes = data.get("nodes")
    if not isinstance(nodes, list) or not nodes:
        raise BuildError("constellation: no nodes")
    ids, positions = set(), {(50, 50)}
    for node in nodes:
        if not all(text_field(node, key) for key in ("id", "label", "title")):
            raise BuildError("constellation: node needs id, label and title")
        nid = node["id"]
        if nid in ids or not re.fullmatch(r"[a-z][a-z0-9-]*", nid):
            raise BuildError(f"constellation: invalid or duplicate node id: {nid}")
        ids.add(nid)
        pos = node.get("position")
        if (not isinstance(pos, list) or len(pos) != 2
                or any(type(value) is not int or not 0 < value < 100 for value in pos)
                or tuple(pos) in positions):
            raise BuildError(f"constellation: invalid or duplicate node position: {nid}")
        positions.add(tuple(pos))
        entries = node.get("evidence")
        if not isinstance(entries, list) or not entries:
            raise BuildError(f"constellation: no evidence for {nid}")
        for entry in entries:
            if (not text_field(entry, "text") or not text_field(entry, "kind")
                    or entry["kind"] not in EVIDENCE_LABELS):
                raise BuildError(f"constellation: invalid evidence for {nid}")
            source = entry.get("source")
            if (not text_field(source, "label") or not text_field(source, "url")
                    or not PINNED_SOURCE.fullmatch(source["url"])):
                raise BuildError(f"constellation: {nid} needs a commit-pinned public PA source for each entry")
    return nodes


PINNED_PARTS = re.compile(
    r"https://github\.com/holland202/principia-artificialis/blob/([0-9a-f]{40})/([^#]+)"
)


def missing_pinned(pairs, root=ROOT, git=("git",)):
    """Return 'owner -> sha:path' for every (owner, url) whose file is not at its commit in this clone."""
    missing = []
    for owner, url in pairs:
        sha, path = PINNED_PARTS.match(url).groups()
        try:
            result = subprocess.run([*git, "-C", str(root), "cat-file", "-e", f"{sha}:{path}"],
                                    capture_output=True, timeout=30)
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise BuildError(f"could not check pinned sources with git: {exc}")
        if result.returncode != 0:
            missing.append(f"{owner} -> {sha[:7]}:{path}")
    return missing


def check_sources_exist(data, root=ROOT, git=("git",)):
    """Fail closed (C-BUILD) unless every pinned source names a file that exists at its commit in this clone.

    A link pinned to a commit only on a deleted branch, or to a mistyped path, would otherwise render as a
    working-looking source. A clone that lacks the commit (shallow, or a branch never fetched) stops the build
    too: the check cannot tell "not fetched" from "gone", so it does not guess. CI checks out full history.
    """
    pairs = [(node["id"], entry["source"]["url"])
             for node in validate_constellation(data) for entry in node["evidence"]]
    try:
        missing = missing_pinned(pairs, root, git)
    except BuildError as exc:
        raise BuildError(f"constellation: {exc}")
    if missing:
        raise BuildError("constellation: pinned source not found in this clone (fetch all branches, "
                         "or fix the link): " + "; ".join(missing))


def constellation_satellite(node):
    x, y = node["position"]
    distance = ((x - 50) ** 2 + (y - 50) ** 2) ** 0.5
    dx, dy = (50 - y) / distance * 0.2, (x - 50) / distance * 0.2
    style = f"--x:{x}%;--y:{y}%;--dx:{dx:.3f}%;--dy:{dy:.3f}%"
    kind = node["evidence"][0]["kind"]
    return (f'<div class="rc-satellite rc-{kind}" style="{style}">'
            '<span class="rc-spoke" aria-hidden="true"></span>'
            f'<a class="rc-node" href="#rc-detail-{node["id"]}">'
            f'<span class="rc-dot" aria-hidden="true"></span>{E(node["label"])}</a></div>')


def constellation_detail(node):
    entries = []
    for item in node["evidence"]:
        kind, source = item["kind"], item["source"]
        entries.append(
            f'<li class="rc-entry rc-{kind}"><span class="rc-kind">{E(EVIDENCE_LABELS[kind])}</span>'
            f'<p>{E(item["text"])}</p><a href="{E(source["url"])}">{E(source["label"])}</a></li>'
        )
    return (f'<article class="rc-detail" id="rc-detail-{node["id"]}">'
            f'<h3 tabindex="-1">{E(node["title"])}</h3><ul>{"".join(entries)}</ul>'
            '<a class="rc-back" href="#rc-map">Back to map</a></article>')


def render_constellation(data):
    nodes = validate_constellation(data)
    counts = Counter(item["kind"] for node in nodes for item in node["evidence"])
    telemetry = (("Research nodes", len(nodes)), ("Independent study reproductions", counts["reproduced"]),
                 ("Documentary reproductions", counts["documentary"]), ("Failures kept", counts["failure"]))
    metrics = "".join(f'<div><dt>{label}</dt><dd>{count}</dd></div>' for label, count in telemetry)
    legend = "".join(
        f'<li class="rc-{kind}"><span class="rc-dot" aria-hidden="true"></span>{E(label)}</li>'
        for kind, label in EVIDENCE_LABELS.items()
    )
    return ('<div class="rc-layout">\n'
            '<div class="rc-chart"><div class="rc-map" id="rc-map" role="group" '
            'aria-label="Research records" tabindex="-1">\n'
            '<div class="rc-hub" aria-hidden="true"><b>PA</b></div>\n'
            + "\n".join(map(constellation_satellite, nodes))
            + f'\n</div><ul class="rc-legend" aria-label="Evidence labels">{legend}</ul></div>\n'
            f'<div class="rc-inspector"><dl class="rc-telemetry" aria-label="Counts for this map">{metrics}</dl>'
            + "\n".join(map(constellation_detail, nodes))
            + '</div></div>\n'
            f'<p class="rc-snapshot">Sources reviewed <time datetime="{data["reviewedAt"]}">{data["reviewedAt"]}</time>'
            ' · <a href="data/dashboard/research_constellation.json">Source data and provenance</a></p>')


REPRODUCE_KINDS = {"documentary": "Documentary check", "failure": "Kept refutation", "result": "Result"}


def validate_reproduce(data, root=ROOT):
    """Each entry needs pinned sources, repo files that exist, steps, expected output and a negative control."""
    if (not text_field(data, "reviewedAt") or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", data["reviewedAt"])
            or not text_field(data, "provenance")):
        raise BuildError("reproduce: missing review date or provenance")
    report = data.get("report")
    if (not text_field(report, "label") or not text_field(report, "url")
            or not report["url"].startswith("https://github.com/holland202/principia-artificialis/")):
        raise BuildError("reproduce: report link must point into this repository")
    entries = data.get("entries")
    if not isinstance(entries, list) or not entries:
        raise BuildError("reproduce: no entries")
    ids = set()
    for entry in entries:
        eid = entry.get("id") if isinstance(entry, dict) else None
        if not isinstance(eid, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", eid) or eid in ids:
            raise BuildError(f"reproduce: invalid or duplicate entry id: {eid}")
        ids.add(eid)
        for key in ("title", "claim", "status", "needs", "expectedNote", "crossCheck", "doesNotShow"):
            if not text_field(entry, key):
                raise BuildError(f"reproduce: {eid} needs {key}")
        if entry.get("kind") not in REPRODUCE_KINDS:
            raise BuildError(f"reproduce: {eid} has an unknown kind")
        for key in ("steps", "expected"):
            items = entry.get(key)
            if not isinstance(items, list) or not items or not all(isinstance(x, str) and x.strip() for x in items):
                raise BuildError(f"reproduce: {eid} needs non-empty {key}")
        control = entry.get("control")
        if (not all(text_field(control, k) for k in ("command", "what"))
                or not isinstance(control.get("expected"), list) or not control["expected"]
                or not all(isinstance(x, str) and x.strip() for x in control["expected"])):
            raise BuildError(f"reproduce: {eid} needs a negative control with a command and expected output")
        sources = entry.get("sources")
        if not isinstance(sources, list) or not sources:
            raise BuildError(f"reproduce: {eid} needs sources")
        for source in sources:
            if (not text_field(source, "label") or not text_field(source, "url")
                    or not PINNED_SOURCE.fullmatch(source["url"])):
                raise BuildError(f"reproduce: {eid} needs a commit-pinned public PA source for each entry")
        files = entry.get("files")
        if not isinstance(files, list) or not files:
            raise BuildError(f"reproduce: {eid} needs files")
        for name in files:
            if (not isinstance(name, str) or name.startswith("/") or ".." in Path(name).parts
                    or not (root / name).is_file()):
                raise BuildError(f"reproduce: {eid} names a file that is not in the repository: {name}")
    return entries


def check_reproduce_sources(data, root=ROOT, git=("git",)):
    pairs = [(e["id"], s["url"]) for e in validate_reproduce(data, root) for s in e["sources"]]
    try:
        missing = missing_pinned(pairs, root, git)
    except BuildError as exc:
        raise BuildError(f"reproduce: {exc}")
    if missing:
        raise BuildError("reproduce: pinned source not found in this clone: " + "; ".join(missing))


def render_reproduce(data, root=ROOT):
    entries = validate_reproduce(data, root)
    out = []
    for e in entries:
        pre = lambda lines: '<pre class="rp-code"><code>' + E("\n".join(lines)) + "</code></pre>"
        sources = "".join(f'<a href="{E(s["url"])}">{E(s["label"])} ↗</a>' for s in e["sources"])
        files = "".join(f'<a href="{E(REPO + f)}"><code>{E(f)}</code></a>' for f in e["files"])
        c = e["control"]
        out.append(
            f'<article class="card rp-entry rp-{e["kind"]}" id="rp-{e["id"]}">'
            f'<div class="tag">{E(REPRODUCE_KINDS[e["kind"]])}</div><h3>{E(e["title"])}</h3>'
            f'<p><strong>Claim.</strong> {E(e["claim"])}</p>'
            f'<p><strong>Status.</strong> {E(e["status"])}</p>'
            f'<p><strong>Needs.</strong> {E(e["needs"])}</p>'
            f'<h4>Run it</h4>{pre(e["steps"])}'
            f'<h4>Expected</h4>{pre(e["expected"])}<p>{E(e["expectedNote"])}</p>'
            f'<h4>Negative control: the check must catch this</h4><p>{E(c["what"])}</p>'
            f'{pre([c["command"]])}<p>Expected:</p>{pre(c["expected"])}'
            f'<p><strong>Cross-check.</strong> {E(e["crossCheck"])}</p>'
            f'<p><strong>What it does not show.</strong> {E(e["doesNotShow"])}</p>'
            f'<div class="inline-links">{sources}{files}</div></article>')
    report = data["report"]
    return ('<div class="grid grid-top rp-grid">\n' + "\n".join(out) + '\n</div>\n'
            '<p class="rp-report">Ran one? Post your environment (OS, Python, numpy), the full output and any '
            f'difference, even a matching run. <a href="{E(report["url"])}">{E(report["label"])} ↗</a></p>\n'
            f'<p class="rc-snapshot">Entries reviewed <time datetime="{data["reviewedAt"]}">{data["reviewedAt"]}</time>'
            ' · <a href="data/dashboard/reproduce.json">Source data and provenance</a></p>')


def build(page_text, index_text, card_obj, extra_cards=None, constellation=None, reproduce=None):
    featured = validate_card(card_obj)
    extra = load_cards() if extra_cards is None else extra_cards
    if constellation is None:
        constellation = json.loads(CONSTELLATION.read_text(encoding="utf-8"))
    if reproduce is None:
        reproduce = json.loads(REPRODUCE.read_text(encoding="utf-8"))
    ix = parse_index(index_text)
    blocks = {"overview": None,
              "status-board": render_status(ix),
              "egrr-card": render_card(featured),
              "research-cards": render_cards(featured, extra),
              "research-constellation": render_constellation(constellation),
              "reproduce": render_reproduce(reproduce)}
    blocks["overview"] = render_overview(ix, [featured] + [c for _, c in extra])
    out = page_text
    for name, body in blocks.items():
        pat = re.compile(rf"(<!-- generated:{name}:start -->\n).*?(<!-- generated:{name}:end -->)", re.S)
        if len(pat.findall(out)) != 1:
            raise BuildError(f"dashboard.html: marker pair for {name} not found exactly once")
        out = pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), out)
    return out


def main(argv):
    check = "--check" in argv
    try:
        page = PAGE.read_text(encoding="utf-8")
        constellation = json.loads(CONSTELLATION.read_text(encoding="utf-8"))
        check_sources_exist(constellation)
        reproduce = json.loads(REPRODUCE.read_text(encoding="utf-8"))
        check_reproduce_sources(reproduce)
        new = build(page, INDEX.read_text(encoding="utf-8"), json.loads(CARD.read_text(encoding="utf-8")),
                    constellation=constellation, reproduce=reproduce)
    except (OSError, ValueError, BuildError) as exc:
        print(f"COULD NOT BUILD: {exc}")
        return 2
    if check:
        if new != page:
            print("DRIFT: dashboard.html does not match its sources; run python scripts/make_dashboard.py")
            return 1
        print("dashboard.html matches NOTES_INDEX.md and the sources in data/dashboard/")
        return 0
    if new != page:
        PAGE.write_text(new, encoding="utf-8")
        print("dashboard.html updated")
    else:
        print("dashboard.html already current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
