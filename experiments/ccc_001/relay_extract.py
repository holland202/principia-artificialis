"""CCC-001 relay prefix extractor. Registration: RELAY_CHECKPOINTS_PREREG.md (98798ba), frozen at 7d80c0e.

Archival only. It cuts registered prefixes of the PR #172 relay from a raw `gh api` export. It renders no arm-A
prompt and assigns no chat roles: speaker mapping (rule 6) is not frozen and is not implemented here.

Usage:
  gh api repos/holland202/principia-artificialis/issues/172/comments --paginate > EXPORT.json
  python3 experiments/ccc_001/relay_extract.py EXPORT.json --checkpoint 16 [--snapshot PRIOR.json] [--out FILE]

Exit 0: prefix written (or printed). Exit 2: checkpoint MISSING (turn not reached). Exit 3: fail-closed defect.
Nothing is written unless the exit is 0.

Checks beyond frozen rule 3, added after review in relay turn 012 (disclosed in RELAY_EXTRACT_RESULTS.md):
the comment author must be the relay account; the whole 4-line header must be well formed; a turn whose
`updated_at` differs from `created_at` fails closed unless a prior snapshot holds its body (the REST API does not
return earlier bytes, so `original_body_available` is recorded as false).
"""
import argparse
import hashlib
import json
import random
import re
import sys

RELAY_PR = 172
RELAY_ACCOUNT = "holland202"  # both AIs post through Chad's account
CLASSES = {8: "archival (post-hoc only)", 16: "primary", 32: "primary", 24: "secondary", 40: "secondary"}
NOTE_RE = re.compile(r"^note: ccc-relay/(claude|chatgpt)/(\d{3})$")
FOOTER_RE = re.compile(r"\n*---\n_Generated by [^\n]*_\s*\Z")


class Defect(Exception):
    pass


class Missing(Exception):
    pass


def sha(b):
    return hashlib.sha256(b if isinstance(b, bytes) else b.encode("utf-8")).hexdigest()


def load(raw):
    """Parse one export; `gh api --paginate` concatenates one JSON array per page."""
    dec, i, out, txt = json.JSONDecoder(), 0, [], raw.decode("utf-8")
    while i < len(txt):
        if txt[i].isspace():
            i += 1
            continue
        page, i = dec.raw_decode(txt, i)
        out.extend(page)
    return out


def header(body):
    """None if not a relay turn (rule 2); (nnn, speaker) if a well-formed one; Defect if it claims to be one but
    the header is malformed."""
    lines = body.split("\n")
    if len(lines) < 2 or lines[0].rstrip("\r") != "```yaml":
        return None
    m = NOTE_RE.match(lines[1].rstrip("\r"))
    if not m:
        return None
    nnn = int(m.group(2))
    ok = (len(lines) >= 5 and lines[2].startswith("by: ") and "session:" in lines[2]
          and "human review:" in lines[2] and lines[3].startswith("re: ") and lines[4].rstrip("\r") == "```")
    if not ok:
        raise Defect(f"turn {nnn:03d}: malformed header")
    return nnn, m.group(1)


def render(body):
    """Rule 5: drop the leading yaml fence and a trailing `---` + `_Generated by ..._` footer; keep the rest."""
    lines = body.split("\n")
    end = next(i for i in range(1, len(lines)) if lines[i].rstrip("\r") == "```")
    rest = "\n".join(lines[end + 1:]).lstrip("\r\n")
    return FOOTER_RE.sub("", rest)


def extract(comments, k, snapshot=None, checks=True):
    turns, excluded, seen = [], [], {}
    for c in comments:
        try:
            h = header(c["body"])
        except Defect:
            if checks:
                raise
            h = None
        if h is None:
            excluded.append(c["id"])
            continue
        nnn, who = h
        if checks and nnn in seen:
            raise Defect(f"turn {nnn:03d} claimed twice (ids {seen[nnn]} and {c['id']})")
        seen[nnn] = c["id"]
        turns.append((nnn, who, c))
    if not any(n == k for n, _, _ in turns):
        raise Missing(f"checkpoint {k:03d} MISSING: turn not reached")
    pre = sorted((t for t in turns if t[0] <= k), key=lambda t: t[0])
    snap = {t["nnn"]: t for t in (snapshot or {}).get("turns", [])}
    if checks:
        nums = [n for n, _, _ in pre]
        if nums != list(range(1, k + 1)):
            raise Defect(f"gap: turns {sorted(set(range(1, k + 1)) - set(nums))} missing")
        for n, who, c in pre:
            if who != ("claude" if n % 2 else "chatgpt"):
                raise Defect(f"turn {n:03d}: speaker {who} on {'odd' if n % 2 else 'even'} slot")
            if c["user"]["login"] != RELAY_ACCOUNT:
                raise Defect(f"turn {n:03d}: posted by {c['user']['login']}, not the relay account")
        by_time = [n for n, _, c in sorted(pre, key=lambda t: (t[2]["created_at"], t[2]["id"]))]
        if by_time != nums:
            raise Defect("NNN order disagrees with (created_at, id) order")
        for n, _, c in pre:
            b = sha(c["body"])
            if n in snap and snap[n]["body_sha256"] != b:
                raise Defect(f"turn {n:03d}: body differs from snapshot (snapshot governs)")
            if c["updated_at"] != c["created_at"] and n not in snap:
                raise Defect(f"turn {n:03d}: edited ({c['updated_at']}) with no prior snapshot; "
                             f"original_body_available=false")
    out = []
    for n, who, c in pre:
        out.append({"nnn": n, "speaker": who, "comment_id": c["id"], "created_at": c["created_at"],
                    "updated_at": c["updated_at"], "body_sha256": sha(c["body"]),
                    "edited": c["updated_at"] != c["created_at"], "original_body_available": n in snap,
                    "body": c["body"], "rendered": render(c["body"])})
    return {"relay_pr": RELAY_PR, "checkpoint": k, "class": CLASSES.get(k, "not a registered checkpoint"),
            "status": "archival; no arm-A use without Chad's approval", "excluded_comment_ids": excluded,
            "turns": out}


def shuffle_perm(k):
    """Registered construction. Seed text uses the three-digit turn number (e.g. b'...-016'); the frozen text writes
    '<k>' and does not say which form, so this choice is disclosed. Returns new_order[slot-1] = original nnn."""
    rng = random.Random(int(sha(f"ccc-001-relay-shuffle-{k:03d}".encode()), 16))
    odd, even = list(range(1, k + 1, 2)), list(range(2, k + 1, 2))
    rng.shuffle(odd)
    rng.shuffle(even)
    order = []
    for i in range(k):
        order.append(odd[i // 2] if i % 2 == 0 else even[i // 2])
    return order


def dumps(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False, sort_keys=True) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("export")
    ap.add_argument("--checkpoint", type=int, required=True)
    ap.add_argument("--snapshot")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    raw = open(a.export, "rb").read()
    snap = json.load(open(a.snapshot)) if a.snapshot else None
    try:
        p = extract(load(raw), a.checkpoint, snap)
    except Missing as e:
        print(e)
        return 2
    except Defect as e:
        print("DEFECT", e)
        return 3
    p["source_sha256"] = sha(raw)
    s = dumps(p)
    if a.out:
        open(a.out, "w", encoding="utf-8").write(s)
    print(f"checkpoint {a.checkpoint:03d} ({p['class']}): {len(p['turns'])} turns, "
          f"file sha256 {sha(s)}" + (f" -> {a.out}" if a.out else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
